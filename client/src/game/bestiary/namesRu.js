// драконы: цвет — в именительном и родительном падеже
const COLORS = {
  Black: ['чёрный', 'чёрного'],
  Blue: ['синий', 'синего'],
  Brass: ['латунный', 'латунного'],
  Bronze: ['бронзовый', 'бронзового'],
  Copper: ['медный', 'медного'],
  Gold: ['золотой', 'золотого'],
  Green: ['зелёный', 'зелёного'],
  Red: ['красный', 'красного'],
  Silver: ['серебряный', 'серебряного'],
  White: ['белый', 'белого'],
};
const AGES = { Young: 'Молодой', Adult: 'Взрослый', Ancient: 'Древний' };

/** Русское название монстра SRD (пустая строка — не знаем) */
export function nameRu(name) {
  const n = String(name || '').trim();
  if (NAMES[n]) return NAMES[n];
  let m = /^(Black|Blue|Brass|Bronze|Copper|Gold|Green|Red|Silver|White) Dragon Wyrmling$/.exec(n);
  if (m) return `Вирмлинг ${COLORS[m[1]][1]} дракона`;
  m = /^(Young|Adult|Ancient) (Black|Blue|Brass|Bronze|Copper|Gold|Green|Red|Silver|White) Dragon$/.exec(n);
  if (m) return `${AGES[m[1]]} ${COLORS[m[2]][0]} дракон`;
  return '';
}

